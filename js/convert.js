const ITEM_TEXT_FIELDS = ['title', 'subtitle', 'desc', 'note'];

/** 转换单段文字，返回 { text, count } */
export function convertText(input) {
  let s = String(input == null ? '' : input);
  let count = 0;
  for (const [ja, zh] of JP_TO_SC) {
    if (s.indexOf(ja) !== -1) {
      const parts = s.split(ja);
      count += parts.length - 1;
      s = parts.join(zh);
    }
  }
  return { text: s, count };
}

/**
 * 就地转换整个状态里的作品卡文本。
 * 返回替换总次数（0 表示没有需要替换的用词）。
 */
export function convertStateItems(state) {
  let total = 0;
  (state.sections || []).forEach(section => {
    (section.items || []).forEach(item => {
      ITEM_TEXT_FIELDS.forEach(field => {
        const res = convertText(item[field]);
        if (res.count > 0) {
          item[field] = res.text;
          total += res.count;
        }
      });
    });
  });
  return total;
}
